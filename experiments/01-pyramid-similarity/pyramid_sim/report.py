"""Markdown tables from results_*.json -> results/tables.md."""

from __future__ import annotations

import json

from . import config as C
from .figures import LEVEL_LABEL, PREC_METHODS
from .queries import QUERIES

EXTRA = ["M3 slot 6 dot, negated", "M3 band 5-8 dot, negated"]


def _load(tag):
    p = C.RESULTS / f"results_{tag}.json"
    return json.loads(p.read_text()) if p.exists() else None


def precision_table(res, k, suffix=""):
    keys = [q.key for q in QUERIES]
    lines = ["| method | " + " | ".join(keys) + " |", "|---|" + "---:|" * len(keys)]
    lines.append("| *base rate (random pixel)* | " + " | ".join(
        f"*{res['queries'][q]['base_rate_match']:.3f}*" for q in keys) + " |")
    for name in PREC_METHODS:
        vals = [res["queries"][q]["methods"][name][f"p@{k}{suffix}"] for q in keys]
        lines.append(f"| {name} | " + " | ".join(f"{v:.2f}" for v in vals) + " |")
    lines.append("| *inverse base rate* | " + " | ".join(
        f"*{res['queries'][q]['base_rate_inverse']:.3f}*" for q in keys) + " |")
    for name in EXTRA:
        vals = [res["queries"][q]["methods"][name][f"p@{k}{suffix}"] for q in keys]
        lines.append(f"| {name} (vs inverse) | " + " | ".join(f"{v:.2f}" for v in vals) + " |")
    return "\n".join(lines)


def sensitivity_table(res):
    keys = [q.key for q in QUERIES]
    lines = ["| level k | cell | " + " | ".join(f"{q} cos k / slot k" for q in keys) + " |",
             "|---|---|" + "---:|" * len(keys)]
    for k in range(1, 11):
        row = []
        for q in keys:
            qr = res["queries"][q]
            m1 = qr["methods"]["M0 pixel cos" if k == 1 else f"M1 level {k} cos"]["p@200"]
            sl = qr["sensitivity"][f"slot {k} dot"]["p@200"]
            row.append(f"{m1:.2f} / {sl:.2f}")
        lines.append(f"| {k} | {LEVEL_LABEL[k]} | " + " | ".join(row) + " |")
    return "\n".join(lines)


def agreement_table(res):
    keys = [q.key for q in QUERIES]
    pairs = list(res["queries"][keys[0]]["layout_agreement"])
    lines = ["| pair | " + " | ".join(keys) + " |", "|---|" + "---:|" * len(keys)]
    for p in pairs:
        cells = [res["queries"][q]["layout_agreement"][p] for q in keys]
        lines.append(f"| {p} | " + " | ".join(
            f"J {c['top200_jaccard']:.2f}, ρ {c['cell_spearman']:.2f}" for c in cells) + " |")
    return "\n".join(lines)


def state_table(res):
    """Share of top-200 hits whose dominant class at 160 m / 1.28 km equals the query's."""
    keys = [q.key for q in QUERIES]
    names = ["M0 pixel cos", "M2 means, equal w", "M2 means, L2", "M3 diffs, L2", "M3 band 5-8 dot"]
    lines = ["| method | " + " | ".join(f"{q} (160 m / 1.28 km)" for q in keys) + " |",
             "|---|" + "---:|" * len(keys)]
    for n in names:
        lines.append(f"| {n} | " + " | ".join(
            f"{res['queries'][q]['methods'][n]['dom16_same_as_query']:.2f} / "
            f"{res['queries'][q]['methods'][n]['dom128_same_as_query']:.2f}" for q in keys) + " |")
    return "\n".join(lines)


def toy_table(res, qkey="Q1"):
    """The toy's categories for Q1 hits, by dominant class at 160 m / 1.28 km."""
    cats = {"tree/open": "island (pattern)", "tree/tree": "forest interior",
            "open/tree": "clearing in forest", "open/open": "open grassland"}
    names = ["M0 pixel cos", "M2 means, L2", "M2 means, equal w", "M3 diffs, L2",
             "M3 band 5-8 dot", "M3 band 5-8 dot, negated"]
    lines = ["| method (top 200) | " + " | ".join(cats.values()) + " | other |",
             "|---|" + "---:|" * (len(cats) + 1)]
    for n in names:
        d = res["queries"][qkey]["methods"][n]["dom16_dom128_top200"]
        vals = [d.get(c, 0) for c in cats]
        lines.append(f"| {n} | " + " | ".join(str(v) for v in vals) + f" | {200 - sum(vals)} |")
    return "\n".join(lines)


def write_tables():
    res = _load("128d")
    r64 = _load("64d")
    out = ["# Result tables (generated by `pyramid_sim.report`)", ""]
    out += ["## precision@50, 128 dims", "", precision_table(res, 50), ""]
    out += ["## precision@200, 128 dims", "", precision_table(res, 200), ""]
    out += ["## precision@200, 128 dims, excluding every cell within 640 m of the query",
            "(added after the first run; see README)", "", precision_table(res, 200, "_x640"), ""]
    if r64:
        out += ["## precision@200, 64-dim Matryoshka prefix", "", precision_table(r64, 200), ""]
    out += ["## precision@200 by level: single-level cosine on means vs single difference slot",
            "", sensitivity_table(res), ""]
    out += ["## do the layouts rank alike? (top-200 Jaccard J, Spearman ρ over 16 384 cells)",
            "", agreement_table(res), ""]
    out += ["## state agreement: share of top-200 hits with the query's dominant class",
            "", state_table(res), ""]
    out += ["## Q1 hits in the toy's categories (dominant class at 160 m / 1.28 km)", "",
            toy_table(res), ""]
    (C.RESULTS / "tables.md").write_text("\n".join(out))


if __name__ == "__main__":
    write_tables()
